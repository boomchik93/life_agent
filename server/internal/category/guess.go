// Guess finds the category of an event by the words of its title: one of
// study, work, sport, hobby, rest, chores. It is a fallback for events the
// user put into the calendar by hand; ok is false when no word points
// anywhere, and the caller keeps its own default.
func Guess(title string) (cat string, ok bool) {
	key := Normalize(title)
	if key == "" {
		return "", false
	}
	words := strings.Fields(key)
	padded := " " + key + " "
	for _, r := range rules {
		if r.matches(words, padded) {
			return r.category, true
		}
	}
	return "", false
}

func (r rule) matches(words []string, padded string) bool {
	for _, p := range r.phrases {
		if strings.Contains(padded, " "+p+" ") {
			return true
		}
	}
	for _, w := range words {
		for _, x := range r.words {
			if w == x {
				return true
			}
		}
		for _, s := range r.stems {
			if strings.Contains(s, " ") {
				if strings.Contains(padded, " "+s) {
					return true
				}
				continue
			}
			if strings.HasPrefix(w, s) {
				return true
			}
		}
	}
	return false
}
